                                :aria-expanded="open.toString()" aria-haspopup="true" aria-label="More actions">⋯</button>

                        <div x-show="open" x-cloak @click.away="open = false" role="menu"
                             class="absolute right-0 z-20 mt-2 w-56 rounded-lg border border-line bg-surface shadow-lg py-1">
                            <form action="{{ route('tasks.remind', $task) }}" method="POST">
                                @csrf
                                <button type="submit" role="menuitem"
                                        class="block w-full text-left px-4 py-2 text-sm text-ink bg-surface hover:bg-surface-2 border-0 cursor-pointer">
                                    Remind me of the due date
                                </button>
                            </form>
                            <form action="{{ route('tasks.destroy', $task) }}" method="POST" data-confirm="Move this task to trash?">
                                @csrf
                                @method('DELETE')
                                <button type="submit" role="menuitem"
                                        class="block w-full text-left px-4 py-2 text-sm text-danger bg-surface hover:bg-danger-soft border-0 cursor-pointer">
                                    Move to trash
                                </button>
                            </form>
