        $show = function ($value) {
            if ($value === null || $value === '') {
                return '-';
            }
            if (is_bool($value)) {
                return $value ? 'yes' : 'no';
            }
            return (string) $value;
        };
        $canWrite = auth()->user()->can('update', $task);
    @endphp

    <div class="wrap page">
        <nav class="text-sm text-muted mb-3" aria-label="You are here">
            @if ($task->project)
                <a class="text-muted hover:text-ink" href="{{ route('projects.show', $task->project) }}">{{ $task->project->name }}</a>
            @else
                <a class="text-muted hover:text-ink" href="{{ route('tasks.index') }}">Tasks</a>
            @endif
            <span class="mx-1" aria-hidden="true">/</span>
            <span class="text-ink">#{{ $task->id }}</span>
        </nav>

        <header class="flex flex-wrap items-start justify-between gap-4">
            <div class="min-w-0">
                <h1 class="text-3xl">{{ $task->title }}</h1>
                <div class="item-tags mt-2">
                    <span class="badge {{ $task->statusBadge() }}">{{ $task->statusLabel() }}</span>
                    <span class="badge {{ $task->priorityBadge() }}">{{ $task->priorityLabel() }} priority</span>
                    @if ($task->isOverdue())
                        <span class="badge badge-danger">overdue</span>
                    @endif
                </div>
            </div>

            <div class="flex items-center gap-2">
