                    </ul>
                </section>

                {{-- Audit trail: written by the TaskObserver, not by the controller. --}}
                <section class="panel panel-pad" aria-labelledby="history-title">
                    <h2 class="panel-title" id="history-title">History</h2>
                    <p class="text-sm text-muted mt-1">Who did what, and when. Stored in the database, not in the server log.</p>

                    <ol class="list-none m-0 p-0 mt-4 border-l-2 border-line">
                        @forelse ($task->events as $event)
                            @php
                                $meta = $event->metaArray();
                                // updated_at changes on every event: in the diff it is noise.
                                $changed = array_diff_key($meta['changed'] ?? [], ['updated_at' => true]);
                            @endphp
                            <li class="relative pl-5 pb-4">
                                <span class="absolute w-3 h-3 rounded-full bg-surface border-2 border-brand" style="left: -7px; top: 6px" aria-hidden="true"></span>
